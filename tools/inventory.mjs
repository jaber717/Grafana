// Generates docs/dashboard-inventory.md from the dashboards in this repository (offline).  node tools/inventory.mjs [--check]
// --check exits 1 if the committed document is out of date (used by scripts/release-gate.sh).
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, repoDashboards, readJson } from '../scripts/lib/grafana.mjs';

const dsName = new Map(readJson('config/datasources.json').map((d) => [d.uid, d.name]));
const lines = ['# Dashboard inventory', '', '*Generated by `tools/inventory.mjs` from `dashboards/` - do not edit by hand.*', ''];
const flat = (panels) => (panels || []).flatMap((p) => [p, ...flat(p.panels)]);
const dsOf = (o, set) => { if (!o || typeof o !== 'object') return; if (o.datasource && typeof o.datasource === 'object' && o.datasource.uid) set.add(o.datasource.uid); for (const v of Object.values(o)) dsOf(v, set); };

lines.push('| Folder | uid | Title | Panels | Variables | Refresh | Default range | Datasources |', '|---|---|---|---|---|---|---|---|');
const detail = [];
for (const { folderDir, dashboard: d } of repoDashboards()) {
  const panels = flat(d.panels).filter((p) => p.type !== 'row');
  const ds = new Set(); dsOf(d, ds);
  const vars = (d.templating?.list || []).map((v) => v.name);
  lines.push(`| ${folderDir} | \`${d.uid}\` | ${d.title} | ${panels.length} | ${vars.length} | ${d.refresh || '-'} | ${d.time?.from || '-'} to ${d.time?.to || '-'} | ${[...ds].filter((u) => dsName.has(u)).map((u) => dsName.get(u)).join(', ') || '-'} |`);
  detail.push(`## ${d.title} (\`${d.uid}\`, folder ${folderDir})`, '', d.description ? d.description + '\n' : '', `Tags: ${(d.tags || []).join(', ') || '-'}. Variables: ${vars.map((v) => '`' + v + '`').join(', ') || '-'}.`, '', '| Panel | Type |', '|---|---|',
    ...panels.map((p) => `| ${String(p.title || '(untitled)').replace(/\|/g, '/')} | ${p.type} |`), '');
}
const text = lines.concat('', detail).join('\n') + '\n';
const target = join(ROOT, 'docs', 'dashboard-inventory.md');
if (process.argv.includes('--check')) {
  let cur = ''; try { cur = readFileSync(target, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing */ }
  if (cur !== text) { console.error('docs/dashboard-inventory.md is out of date: run node tools/inventory.mjs'); process.exit(1); }
  console.log('dashboard inventory is current');
} else { writeFileSync(target, text); console.log('wrote docs/dashboard-inventory.md'); }
