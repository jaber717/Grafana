// Generates the two report dashboards (Grafana dashboard JSON) for the folder "NOC / Daily Reports".
//   source 'live'  : real datasources - ClickHouse (NetFlow) and the Zabbix datasource plugin (interfaces)
//   source {demo}  : the SAME panels, with only the targets replaced by TestData CSV data from a DEMO fixture
// The dashboards are panel libraries: the report job renders each panel as an image through Grafana's renderer for an explicit
// from/to window, so the dashboards themselves carry no fixed time range other than a sensible default.
import { createHash } from 'node:crypto';
import { NETFLOW_QUERIES, bind } from './queries.mjs';
import { PATTERN, TIERS } from './item-patterns.mjs';

export const PALETTE = { inbound: '#2F6EBA', outbound: '#E0861B', prev: '#8A94A3', ink: '#1F2933', grid: '#E4E7EB', ok: '#2E8B57', warn: '#D98E04', crit: '#C53030', other: '#7A8AA0' };
export const DS_CH = { type: 'grafana-clickhouse-datasource', uid: 'netflow-clickhouse' };
export const DS_ZBX = { type: 'alexanderzobnin-zabbix-datasource', uid: 'zabbix-lab' };
export const DS_DEMO = { type: 'grafana-testdata-datasource', uid: 'report-demo' };
// Top-level folder (the repository's apply/verify/backup tooling manages top-level folders by uid = directory name).
export const FOLDER = { uid: 'noc-daily-reports', title: 'NOC / Daily Reports' };

const fixed = (c) => ({ mode: 'fixed', fixedColor: c });
const byName = (name, props) => ({ matcher: { id: 'byName', options: name }, properties: props });
const color = (name, c) => byName(name, [{ id: 'color', value: fixed(c) }]);

const baseTs = (unit, extra = {}) => ({
  defaults: {
    unit, min: 0, noValue: 'NO DATA',
    color: { mode: 'fixed', fixedColor: PALETTE.inbound },
    custom: { drawStyle: 'line', lineWidth: 2, lineInterpolation: 'linear', fillOpacity: 16, gradientMode: 'opacity', showPoints: 'never', spanNulls: false, axisBorderShow: false, axisSoftMin: 0, axisPlacement: 'auto', stacking: { mode: 'none', group: 'A' }, ...extra },
  },
  overrides: [],
});

function panel(id, title, type, w, h, y, fieldConfig, options, targets, extra = {}) {
  return { id, title, type, gridPos: { x: 0, y, w, h }, transparent: true, fieldConfig, options, targets, ...extra };
}

function tsOptions(legend = true) {
  return { legend: { showLegend: legend, displayMode: 'list', placement: 'bottom', calcs: [] }, tooltip: { mode: 'multi', sort: 'desc' } };
}

// The revision tag fingerprints the panel definitions (queries, targets, layout): the report job refuses to render against a dashboard
// whose revision differs from what the current configuration generates (e.g. after the interface list changed).
export const revisionOf = (panels) => createHash('sha256').update(JSON.stringify(panels)).digest('hex').slice(0, 12);

function dashboard(uid, title, panels, tags, vars = []) {
  return {
    uid, title, tags: ['report', 'daily', ...tags, `rev:${revisionOf(panels)}`], timezone: 'Asia/Riyadh', editable: true, graphTooltip: 1, refresh: '', schemaVersion: 39,
    time: { from: 'now/d-1d', to: 'now/d' }, timepicker: { hidden: false }, templating: { list: vars }, annotations: { list: [] },
    description: 'Generated by grafana-report. Daily report panels: rendered for the previous complete Asia/Riyadh day. Do not edit by hand - regenerate.',
    panels,
  };
}

const DEMO_ROW = (rows, cols) => [cols.join(','), ...rows.map((r) => cols.map((c) => r[c]).join(','))].join('\n');

// ---- targets -------------------------------------------------------------------------------------------------------------------
function chTargets(ids, refPrefix = 'A') {
  return ids.map((id, i) => ({ datasource: DS_CH, editorType: 'sql', format: 0, rawSql: bind(NETFLOW_QUERIES[id].sql, null, { macro: true, variable: true }), refId: String.fromCharCode(refPrefix.charCodeAt(0) + i) }));
}

// DEMO series for time-based panels: fixture rows [{time, <col>: v, ...}] -> one csv_metric_values target per column.
function demoSeries(rows, cols, aliases = {}) {
  return cols.map((c, i) => ({ datasource: DS_DEMO, scenarioId: 'csv_metric_values', stringInput: [...rows.map((r) => (r[c] == null ? 'null' : Math.round(r[c]))), 'null'].join(','), alias: aliases[c] || c, refId: String.fromCharCode(65 + i) }));
}

function demoTable(rows, cols) {
  return [{ datasource: DS_DEMO, scenarioId: 'csv_content', csvContent: DEMO_ROW(rows, cols), refId: 'A' }];
}

// Hidden textbox variables carry the report SCOPE into the panels (the job passes var-<name>=... when it renders), so one dashboard serves every saved scope.
const scopeVar = (name, label, def, description) => ({ type: 'textbox', name, label, description, query: def, current: { text: def, value: def }, options: [{ text: def, value: def, selected: true }], hide: 2 });
export const VAR_EXPORTERS = scopeVar('exp_scope', 'Exporters (scope)', '', 'Comma separated exporter names of the report scope; empty = all exporters.');
export const VAR_IFACES = scopeVar('if_scope', 'Interfaces (scope)', '.*', 'Regular expression of the "<site> <interface> in|out" series of the report scope.');
// per CPU / memory name (precedence order) the hosts that use it: the job sets them so a device is drawn from ONE item only
export const VAR_TIER_HOSTS = (kind) => TIERS[kind].map((_, i) => scopeVar(`${kind}_hosts_${i}`, `${kind} hosts, name ${i + 1}`, i === 0 ? '/.*/' : '/^$/', 'Zabbix host filter of the devices whose CPU / memory comes from the configured name number ' + (i + 1) + '.'));
export const VAR_HOSTS = scopeVar('hosts', 'Devices (scope)', '/.*/', 'Zabbix host filter (regular expression literal) of the report scope.');

// ---- NetFlow dashboard ---------------------------------------------------------------------------------------------------------
export function netflowDashboard(source = 'live') {
  const demo = source !== 'live' ? source.demo : null;
  const T = (id, cols, aliases) => (demo ? demoSeries(demo[id], cols, aliases) : chTargets([id]));
  const trendFc = baseTs('bps');
  trendFc.overrides = [color('Inbound', PALETTE.inbound), color('Outbound', PALETTE.outbound)];
  const cmpFc = baseTs('bps');
  cmpFc.defaults.custom.fillOpacity = 8;
  cmpFc.overrides = [
    byName('Report day', [{ id: 'color', value: fixed(PALETTE.inbound) }, { id: 'custom.fillOpacity', value: 18 }]),
    byName('Previous day', [{ id: 'color', value: fixed(PALETTE.prev) }, { id: 'custom.lineStyle', value: { fill: 'dash', dash: [8, 6] } }, { id: 'custom.fillOpacity', value: 0 }, { id: 'custom.lineWidth', value: 1.5 }]),
  ];
  const hourFc = baseTs('decbytes', { drawStyle: 'bars', fillOpacity: 88, lineWidth: 0, gradientMode: 'none', barAlignment: 1, stacking: { mode: 'normal', group: 'A' } });
  hourFc.overrides = [color('Inbound', PALETTE.inbound), color('Outbound', PALETTE.outbound)];
  const pieFc = { defaults: { unit: 'decbytes', decimals: 1, noValue: 'NO DATA', color: { mode: 'palette-classic' } }, overrides: [color('TCP', PALETTE.inbound), color('UDP', PALETTE.outbound), color('ICMP', '#5F9E6E'), color('Other', PALETTE.other)] };
  const barFc = { defaults: { unit: 'decbytes', noValue: 'NO DATA', custom: { fillOpacity: 90, lineWidth: 0, gradientMode: 'none', axisBorderShow: false } }, overrides: [color('InboundBytes', PALETTE.inbound), color('OutboundBytes', PALETTE.outbound), byName('InboundBytes', [{ id: 'displayName', value: 'Inbound' }, { id: 'color', value: fixed(PALETTE.inbound) }]), byName('OutboundBytes', [{ id: 'displayName', value: 'Outbound' }, { id: 'color', value: fixed(PALETTE.outbound) }])] };
  const barOpts = (x) => ({ orientation: 'horizontal', xField: x, stacking: 'normal', showValue: 'never', barWidth: 0.7, groupWidth: 0.7, xTickLabelRotation: 0, legend: { showLegend: true, displayMode: 'list', placement: 'bottom' }, tooltip: { mode: 'multi', sort: 'none' } });

  const panels = [
    panel(1, 'Traffic by direction - 5-minute average', 'timeseries', 24, 10, 0, trendFc, tsOptions(), T('trend', ['Inbound', 'Outbound'])),
    panel(2, 'Report day vs previous day', 'timeseries', 12, 9, 10, cmpFc, tsOptions(),
      demo ? [...demoSeries(demo.trend_total, ['Report day']), { ...demoSeries(demo.trend_prev, ['Previous day'])[0], refId: 'B' }] : chTargets(['trend_total', 'trend_prev'])),
    panel(3, 'Hourly volume', 'timeseries', 12, 9, 10, hourFc, tsOptions(), T('hourly', ['Inbound', 'Outbound'])),
    panel(4, 'Protocol mix (volume)', 'piechart', 8, 9, 19, pieFc,
      { pieType: 'donut', displayLabels: [], legend: { showLegend: true, displayMode: 'list', placement: 'bottom', values: ['percent'] }, reduceOptions: { values: true, calcs: [], fields: '/^Bytes$/' }, tooltip: { mode: 'single' } },
      demo ? demoTable(demo.protocols, ['Protocol', 'Bytes']) : chTargets(['protocols']), { transformations: [] }),
    panel(5, 'Traffic by site', 'barchart', 8, 9, 19, barFc, barOpts('Site'), demo ? demoTable(demo.by_site, ['Site', 'InboundBytes', 'OutboundBytes']) : chTargets(['by_site'])),
    panel(6, 'Traffic by ISP / provider', 'barchart', 8, 9, 19, barFc, barOpts('Provider'), demo ? demoTable(demo.by_isp, ['Provider', 'InboundBytes', 'OutboundBytes']) : chTargets(['by_isp'])),
  ];
  return dashboard('rpt-netflow-daily', demo ? 'DEMO - Daily NetFlow Traffic Report' : 'Daily NetFlow Traffic Report', panels, ['netflow'], [VAR_EXPORTERS]);
}

// ---- Interface dashboard -------------------------------------------------------------------------------------------------------
// The Zabbix datasource names series after the ITEM; the display name comes from the setAlias function (a plain `alias` property is ignored)
export const zbxTarget = (host, item, refId, scale = null, alias = null) => ({
  datasource: DS_ZBX, queryType: '0', refId, resultFormat: 'time_series',
  group: { filter: '/.*/' }, host: { filter: host }, application: { filter: '' }, itemTag: { filter: '' }, item: { filter: item },
  functions: [
    { def: { name: 'groupBy', category: 'Transform', params: [{ name: 'interval', type: 'string' }, { name: 'function', options: ['avg', 'min', 'max', 'sum', 'count', 'median', 'first', 'last'], type: 'string' }], defaultParams: ['1m', 'avg'] }, params: ['5m', 'avg'], added: false },
    ...(scale ? [{ def: { name: 'scale', category: 'Transform', params: [{ name: 'factor', type: 'float' }], defaultParams: [100] }, params: [scale], added: false }] : []),
    ...(alias ? [{ def: { name: 'setAlias', category: 'Alias', params: [{ name: 'alias', type: 'string' }], defaultParams: [] }, params: [alias], added: false }] : []),
  ],
  options: { showDisabledItems: false, skipEmptyValues: false, disableDataAlignment: false, useZabbixValueMapping: false },
  table: { skipEmptyValues: false }, trigger: { filter: '' }, tags: { filter: '' }, proxy: { filter: '' },
});

export function interfacePanelId(index) {
  return 10 + index;
}

// cfg = loadInterfaceConfig(...) result. demo = {byKey: {key: [{time, Inbound, Outbound}]}} for the DEMO variant.
export function interfaceDashboard(cfg, source = 'live') {
  const demo = source !== 'live' ? source.demo : null;
  const panels = [];
  cfg.interfaces.forEach((it, i) => {
    const fc = baseTs('bps');
    if (it.speedBps) { fc.defaults.max = it.speedBps; fc.defaults.thresholds = { mode: 'absolute', steps: [{ color: 'transparent', value: null }, { color: PALETTE.warn, value: it.speedBps * 0.7 }, { color: PALETTE.crit, value: it.speedBps * 0.9 }] }; fc.defaults.custom.thresholdsStyle = { mode: 'dashed' }; }
    fc.overrides = [color('Inbound', PALETTE.inbound), color('Outbound', PALETTE.outbound)];
    const targets = demo
      ? demoSeries(demo.byKey[it.key], ['Inbound', 'Outbound'])
      : [zbxTarget(it.device, it.inboundItem, 'A', null, 'Inbound'), zbxTarget(it.device, it.outboundItem, 'B', null, 'Outbound')];
    panels.push(panel(interfacePanelId(i), `${it.site} - ${it.interface}${it.description ? ` (${it.description})` : ''}`, 'timeseries', 12, 8, i * 8, fc, tsOptions(), targets, { description: `device=${it.device} group=${it.group}${it.boundary ? ` boundary=${it.boundary}` : ''} speed=${it.speedBps ?? 'unknown'}` }));
  });
  // Peak utilisation ranking: util % series (live: Zabbix scale(100/speed); DEMO: same values) -> reduce(max) -> sort -> top 10
  const rated = cfg.interfaces.filter((it) => it.speedBps);
  const utilTargets = [];
  rated.forEach((it) => {
    for (const [dir, item] of [['in', it.inboundItem], ['out', it.outboundItem]]) {
      const refId = String.fromCharCode(65 + (utilTargets.length % 26)) + (utilTargets.length >= 26 ? String(Math.floor(utilTargets.length / 26)) : '');
      const alias = `${it.site} ${it.interface} ${dir}`;
      const pct = (r) => { const v = r[dir === 'in' ? 'Inbound' : 'Outbound']; return v == null ? 'null' : ((v / it.speedBps) * 100).toFixed(2); };
      utilTargets.push(demo
        ? { datasource: DS_DEMO, scenarioId: 'csv_metric_values', alias, refId, stringInput: [...demo.byKey[it.key].map(pct), 'null'].join(',') }
        : zbxTarget(it.device, item, refId, 100 / it.speedBps, alias));
    }
  });
  const utilFc = { defaults: { unit: 'percent', decimals: 1, min: 0, max: 100, noValue: 'NO DATA', color: { mode: 'thresholds' }, thresholds: { mode: 'absolute', steps: [{ color: PALETTE.inbound, value: null }, { color: PALETTE.warn, value: 70 }, { color: PALETTE.crit, value: 90 }] } }, overrides: [] };
  panels.unshift(panel(2, 'Peak utilisation by interface and direction (top 10, 5-minute averages)', 'bargauge', 24, 9, 0, utilFc,
    { orientation: 'horizontal', displayMode: 'gradient', valueMode: 'color', namePlacement: 'left', showUnfilled: true, sizing: 'auto', minVizHeight: 14, text: { titleSize: 11, valueSize: 13 }, reduceOptions: { values: true, calcs: [], fields: '/^Max$/' }, legend: { showLegend: false } },
    utilTargets, { transformations: [{ id: 'reduce', options: { mode: 'seriesToRows', reducers: ['max'], includeTimeField: false } }, { id: 'filterByValue', options: { type: 'include', match: 'any', filters: [{ fieldName: 'Field', config: { id: 'regex', options: { value: '${if_scope:raw}' } } }] } }, { id: 'sortBy', options: { fields: {}, sort: [{ field: 'Max', desc: true }] } }, { id: 'limit', options: { limitField: 10 } }] }));
  return dashboard('rpt-interface-daily', demo ? 'DEMO - Daily Interface Traffic Report' : 'Daily Interface Traffic Report', panels, ['interfaces', 'zabbix'], [VAR_IFACES]);
}

// ---- Network Health dashboard --------------------------------------------------------------------------------------------------------
// The devices come from the ${hosts:raw} variable (a Zabbix host-filter regex literal), so the same dashboard serves every saved scope and any
// device added to Zabbix later. DEMO: the same panels with TestData series per device.
const healthTarget = (item, refId, fns = [], hostVar = 'hosts') => ({
  datasource: DS_ZBX, queryType: '0', refId, resultFormat: 'time_series', group: { filter: '/.*/' }, host: { filter: `\${${hostVar}:raw}` }, application: { filter: '' }, itemTag: { filter: '' }, item: { filter: item },
  functions: [{ def: { name: 'groupBy', category: 'Transform', params: [{ name: 'interval', type: 'string' }, { name: 'function', options: ['avg', 'min', 'max', 'sum', 'count', 'median', 'first', 'last'], type: 'string' }], defaultParams: ['1m', 'avg'] }, params: ['5m', 'avg'], added: false }, ...fns],
  options: { showDisabledItems: false, skipEmptyValues: false, disableDataAlignment: false, useZabbixValueMapping: false }, table: { skipEmptyValues: false }, trigger: { filter: '' }, tags: { filter: '' }, proxy: { filter: '' },
});
const scaleFn = (n) => ({ def: { name: 'scale', category: 'Transform', params: [{ name: 'factor', type: 'float' }], defaultParams: [100] }, params: [n], added: false });
const aliasFn = (a) => ({ def: { name: 'setAlias', category: 'Alias', params: [{ name: 'alias', type: 'string' }], defaultParams: [] }, params: [a], added: false });
const HOSTNAME = '${__field.labels.host}';

// devices = the DEMO devices (only used to build the TestData targets); live dashboards do not depend on the device list
// the timeline draws one cell per 30 minutes (the minimum of its 5-minute buckets, like the live groupBy('30m','min'))
const downsampleMin = (a, n) => (n <= 1 ? a : Array.from({ length: Math.ceil(a.length / n) }, (_, i) => Math.min(...a.slice(i * n, i * n + n))));
export function healthDashboard(source = 'live', devices = []) {
  const demo = source !== 'live' ? source.demo : null;
  // like the live queries, a device without samples draws no series
  const demoSeries_ = (key, scale = 1, minOf = 1) => devices.filter((d) => (demo.byHost[d.host]?.[key] || []).length).map((d, i) => ({ datasource: DS_DEMO, scenarioId: 'csv_metric_values', alias: d.host, refId: String.fromCharCode(65 + i), stringInput: [...downsampleMin(demo.byHost[d.host]?.[key] || [], minOf).map((v) => (v == null ? 'null' : Math.round(v * scale * 100) / 100)), 'null'].join(',') }));
  const tsFc = (max) => { const fc = baseTs('percent', { fillOpacity: 6 }); fc.defaults.max = max; fc.defaults.decimals = 0; fc.defaults.color = { mode: 'palette-classic' }; if (!demo) fc.defaults.displayName = HOSTNAME; return fc; };
  const timelineFc = { defaults: { noValue: 'NO DATA', color: { mode: 'thresholds' }, thresholds: { mode: 'absolute', steps: [{ color: PALETTE.crit, value: null }, { color: PALETTE.ok, value: 0.5 }] },
    mappings: [{ type: 'range', options: { from: 0.5, to: 1, result: { color: PALETTE.ok, text: 'UP', index: 0 } } }, { type: 'range', options: { from: 0, to: 0.4999, result: { color: PALETTE.crit, text: 'DOWN', index: 1 } } }],
    custom: { fillOpacity: 90, lineWidth: 0 } }, overrides: [] };
  if (!demo) timelineFc.defaults.displayName = HOSTNAME;
  const barFc = { defaults: { unit: 'percent', decimals: 1, min: 0, max: 100, noValue: 'NO DATA', color: { mode: 'thresholds' }, thresholds: { mode: 'absolute', steps: [{ color: PALETTE.crit, value: null }, { color: PALETTE.warn, value: 99 }, { color: PALETTE.ok, value: 99.9 }] } }, overrides: [] };
  const panels = [
    panel(1, 'Availability timeline (ICMP, 30-minute cells)', 'status-history', 24, 8, 0, timelineFc, { showValue: 'never', rowHeight: 0.82, colWidth: 1, cellGap: 0, legend: { showLegend: false }, tooltip: { mode: 'single' } },
      demo ? demoSeries_('ping', 1, 6) : [(() => { const t = healthTarget(PATTERN.icmp, 'A'); t.functions[0].params = ['30m', 'min']; return t; })()]),
    panel(2, 'Availability by device (lowest 9)', 'bargauge', 8, 9, 8, barFc,
      { orientation: 'horizontal', displayMode: 'basic', valueMode: 'color', namePlacement: 'left', showUnfilled: true, sizing: 'auto', minVizHeight: 14, text: { titleSize: 11, valueSize: 11 }, reduceOptions: { values: true, calcs: [], fields: '/^Mean$/' }, legend: { showLegend: false } },
      demo ? demoSeries_('ping', 100) : [healthTarget(PATTERN.icmp, 'A', [scaleFn(100), aliasFn('$__zbx_host')])],
      { transformations: [{ id: 'reduce', options: { mode: 'seriesToRows', reducers: ['mean'], includeTimeField: false } }, { id: 'sortBy', options: { fields: {}, sort: [{ field: 'Mean' }] } }, { id: 'limit', options: { limitField: 9 } }] }),
    panel(3, 'CPU utilisation (5-minute average)', 'timeseries', 8, 9, 8, tsFc(100), tsOptions(true), demo ? demoSeries_('cpu') : TIERS.cpu.map((p, i) => healthTarget(p, `cpu${i}`, [], `cpu_hosts_${i}`))),
    panel(4, 'Memory utilisation (5-minute average)', 'timeseries', 8, 9, 8, tsFc(100), tsOptions(true), demo ? demoSeries_('mem') : TIERS.memory.map((p, i) => healthTarget(p, `mem${i}`, [], `memory_hosts_${i}`))),
  ];
  panels[2].gridPos.x = 8; panels[3].gridPos.x = 16;
  return dashboard('rpt-health-daily', demo ? 'DEMO - Daily Network Health Report' : 'Daily Network Health Report', panels, ['health', 'zabbix'], [VAR_HOSTS, ...VAR_TIER_HOSTS('cpu'), ...VAR_TIER_HOSTS('memory')]);
}

// Revision the report job expects to find on Grafana for the current configuration.
export function liveRevision(kind, cfg) {
  const d = kind === 'netflow' ? netflowDashboard('live') : kind === 'health' ? healthDashboard('live') : interfaceDashboard(cfg, 'live');
  return d.tags.find((t) => t.startsWith('rev:')).slice(4);
}
